// Static assets: read once at boot, minified, content-hashed (immutable caching), pre-compressed.
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const dir = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'public');

/** Minify CSS: strip comments and whitespace around punctuation (pure string work, no tooling needed). */
const minCss = s => s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\s*\n\s*/g, '').replace(/\s*([{};,>])\s*/g, '$1').replace(/;}/g, '}').trim();
// JS: only strip whole-line comments and indentation (safe: no regex/strings are rewritten).
const minJs = s => s.split('\n').map(l => l.trim()).filter(l => l && !l.startsWith('//')).join('\n');

const files = new Map();
/** Read one file from public/, transform it, content-hash its name, pre-compress it (brotli + gzip) and register it in `files`. Returns the public URL (/s/<name>.<hash>.<ext>). */
function add(name, ext, type, transform) {
  // transform === null: a binary file (PNG) served as is, without compression.
  const buf = transform ? Buffer.from(transform(fs.readFileSync(path.join(dir, name), 'utf8'))) : fs.readFileSync(path.join(dir, name));
  const hash = crypto.createHash('sha256').update(buf).digest('base64url').slice(0, 10);
  const url = `/s/${name.replace(/\.\w+$/, '')}.${hash}.${ext}`;
  files.set(url, transform ? {
    type, raw: buf,
    br: zlib.brotliCompressSync(buf, { params: { [zlib.constants.BROTLI_PARAM_QUALITY]: 11 } }),
    gz: zlib.gzipSync(buf, { level: 9 }),
  } : { type, raw: buf });
  return url;
}

export const assets = {
  css: add('app.css', 'css', 'text/css; charset=utf-8', minCss),
  js: add('app.js', 'js', 'text/javascript; charset=utf-8', minJs),
  adminCss: add('admin.css', 'css', 'text/css; charset=utf-8', minCss),
  adminJs: add('admin.js', 'js', 'text/javascript; charset=utf-8', minJs),
  og: add('og.png', 'png', 'image/png', null),
  touch: add('touch-icon.png', 'png', 'image/png', null),
  icon: add('favicon.svg', 'svg', 'image/svg+xml', s => s.trim()),
  // Logo (generated by scripts/build-logo.js): animated + reduced-motion variants, light + dark.
  logoLight: add('logo-light.svg', 'svg', 'image/svg+xml', s => s.trim()),
  logoDark: add('logo-dark.svg', 'svg', 'image/svg+xml', s => s.trim()),
  logoStaticLight: add('logo-static-light.svg', 'svg', 'image/svg+xml', s => s.trim()),
  logoStaticDark: add('logo-static-dark.svg', 'svg', 'image/svg+xml', s => s.trim()),
};
export const assetFiles = files;
